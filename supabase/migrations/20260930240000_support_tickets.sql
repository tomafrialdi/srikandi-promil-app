-- Support tickets: inbox from in-app help, website contact form and WhatsApp.
-- Tickets, their message thread (customer / agent / internal note / system event) and reusable macros.

create table public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 4800) unique,
  user_id uuid references public.app_users (id) on delete set null,
  requester_name text not null check (char_length(requester_name) between 2 and 80),
  requester_email text check (char_length(requester_email) <= 120),
  channel text not null check (channel in ('app', 'web', 'whatsapp')),
  category text not null check (category in ('bug', 'billing', 'privacy', 'partner', 'integrations', 'account', 'medical', 'other')),
  subject text not null check (char_length(subject) between 3 and 140),
  priority text not null default 'medium' check (priority in ('high', 'medium', 'low')),
  status text not null default 'open' check (status in ('open', 'pending', 'resolved')),
  assigned_to uuid references public.admin_profiles (id) on delete set null,
  escalated_to text check (escalated_to in ('engine')),
  tags text[] not null default '{}' check (cardinality(tags) <= 8),
  -- Snapshot of the requester's app at the time of the ticket: { platform, app_version, plan }.
  context jsonb not null default '{}',
  first_response_at timestamptz,
  resolved_at timestamptz,
  csat smallint check (csat between 1 and 5),
  csat_comment text check (char_length(csat_comment) <= 300),
  created_by uuid references public.admin_profiles (id) on delete set null,
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index support_tickets_status_idx on public.support_tickets (status, last_message_at desc);
create index support_tickets_assignee_idx on public.support_tickets (assigned_to) where status <> 'resolved';
create index support_tickets_user_idx on public.support_tickets (user_id);

create trigger support_tickets_set_updated_at
  before update on public.support_tickets
  for each row execute function public.set_updated_at();

create table public.support_messages (
  id bigint generated always as identity primary key,
  ticket_id uuid not null references public.support_tickets (id) on delete cascade,
  kind text not null check (kind in ('customer', 'agent', 'note', 'event')),
  author_id uuid references public.admin_profiles (id) on delete set null,
  author_label text not null,
  body text not null check (char_length(body) between 1 and 4000),
  attachments jsonb not null default '[]' check (jsonb_typeof(attachments) = 'array' and jsonb_array_length(attachments) <= 6),
  created_at timestamptz not null default now()
);
create index support_messages_ticket_idx on public.support_messages (ticket_id, created_at, id);

create table public.support_macros (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 2 and 60),
  shortcut text not null unique check (shortcut ~ '^/[a-z0-9-]{2,24}$'),
  body text not null check (char_length(body) between 2 and 2000),
  uses integer not null default 0,
  created_by uuid references public.admin_profiles (id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.support_tickets enable row level security;
alter table public.support_messages enable row level security;
alter table public.support_macros enable row level security;

-- Roles that can see the inbox, and the ones that can answer.
create function analytics_private.require_support_view()
returns void
language plpgsql
stable
set search_path = ''
as $$
begin
  if analytics_private.console_role() not in ('super_admin', 'admin', 'support_agent', 'analyst', 'medical_reviewer', 'engine_engineer') then
    raise exception 'your role is not allowed to view support tickets' using errcode = '42501';
  end if;
end;
$$;

-- Answering: support staff on any ticket; the engine team only on tickets escalated to them.
create function analytics_private.require_support_act(p_ticket uuid)
returns void
language plpgsql
stable
set search_path = ''
as $$
begin
  if analytics_private.console_role() in ('super_admin', 'admin', 'support_agent') then
    return;
  end if;
  if analytics_private.console_role() = 'engine_engineer'
     and exists (select 1 from public.support_tickets where id = p_ticket and escalated_to = 'engine') then
    return;
  end if;
  raise exception 'your role is not allowed to work on this ticket' using errcode = '42501';
end;
$$;

-- "Dewi (Support · Midwife)": first name + short role + job title when it adds something.
create function analytics_private.support_author_label(p_admin uuid)
returns text
language sql
stable
set search_path = ''
as $$
  select split_part(p.full_name, ' ', 1) || ' (' ||
    case p.role when 'support_agent' then 'Support' when 'engine_engineer' then 'Engine team' when 'medical_reviewer' then 'Medical' else 'Admin' end ||
    coalesce(' · ' || nullif(nullif(p.job_title, 'Support agent'), 'Engine engineer'), '') || ')'
  from public.admin_profiles p where p.id = p_admin
$$;

create function analytics_private.support_add_event(p_ticket uuid, p_body text)
returns void
language sql
set search_path = ''
as $$
  insert into public.support_messages (ticket_id, kind, author_id, author_label, body)
  values (p_ticket, 'event', (select auth.uid()), 'System', p_body)
$$;
