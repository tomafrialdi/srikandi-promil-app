-- Audit log companions: security alerts (raised by detection rules), UU PDP data subject requests,
-- saved filter views and "flag for DPO" marks.

create table public.audit_alerts (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 521) unique,
  rule_key text not null,
  severity text not null check (severity in ('high', 'medium', 'low')),
  title text not null,
  detail text not null,
  actor_id uuid references public.admin_profiles (id) on delete set null,
  subject text,
  status text not null default 'open' check (status in ('open', 'in_progress', 'closed')),
  resolution text check (resolution in ('legitimate', 'follow_up', 'misuse')),
  note text check (char_length(note) <= 600),
  assigned_to uuid references public.admin_profiles (id) on delete set null,
  containment jsonb not null default '[]',
  created_at timestamptz not null default now(),
  closed_at timestamptz
);
create index audit_alerts_status_idx on public.audit_alerts (status, created_at desc);

create table public.pdp_requests (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 500) unique,
  type text not null check (type in ('access', 'correction', 'deletion', 'portability')),
  user_id uuid references public.app_users (id) on delete set null,
  subject_ref text not null,
  status text not null default 'new' check (status in ('new', 'in_progress', 'blocked', 'completed')),
  status_note text check (char_length(status_note) <= 200),
  received_at timestamptz not null default now(),
  due_at timestamptz not null,
  completed_at timestamptz,
  owner_id uuid references public.admin_profiles (id) on delete set null,
  identity_check text not null default 'Pending',
  plan_note text,
  systems jsonb not null default '[]' check (jsonb_typeof(systems) = 'array'),
  timeline jsonb not null default '[]' check (jsonb_typeof(timeline) = 'array'),
  certificate_at timestamptz
);
create index pdp_requests_status_idx on public.pdp_requests (status, due_at);

create table public.audit_saved_views (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.admin_profiles (id) on delete cascade,
  name text not null check (char_length(name) between 2 and 50),
  filters jsonb not null,
  shared boolean not null default false,
  created_at timestamptz not null default now()
);
create index audit_saved_views_owner_idx on public.audit_saved_views (owner_id);

create table public.audit_event_flags (
  event_id bigint primary key references public.audit_log (id),
  flagged_by uuid references public.admin_profiles (id) on delete set null,
  note text,
  flagged_at timestamptz not null default now()
);

alter table public.audit_alerts enable row level security;
alter table public.pdp_requests enable row level security;
alter table public.audit_saved_views enable row level security;
alter table public.audit_event_flags enable row level security;

-- Detection rules (thresholds mirror admin_alert_rules): raised when a qualifying audit event is written.
create function public.audit_detect()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text;
  v_n integer;
begin
  if new.actor_id is null then
    return new;
  end if;
  select full_name into v_name from public.admin_profiles where id = new.actor_id;

  if new.action like '%unmask%'
     and coalesce((select enabled from public.admin_alert_rules where key = 'unusual_unmask'), true) then
    select count(*) into v_n from public.audit_log where actor_id = new.actor_id and action like '%unmask%' and created_at > now() - interval '30 minutes';
    if v_n + 1 > 5 and not exists (select 1 from public.audit_alerts where rule_key = 'unusual_unmask' and actor_id = new.actor_id and status <> 'closed' and created_at > now() - interval '2 hours') then
      insert into public.audit_alerts (rule_key, severity, title, detail, actor_id, subject)
      values ('unusual_unmask', 'high', 'Unusual unmask volume', analytics_private.short_name(v_name) || ' unmasked ' || (v_n + 1) || ' profiles in 30 min (normal: ≤ 2/day)', new.actor_id, 'unmask_rate > 5 / 30 min');
    end if;
  end if;

  if new.action = 'auth.failed_2fa' and coalesce((select enabled from public.admin_alert_rules where key = 'failed_2fa'), true) then
    select count(*) into v_n from public.audit_log where actor_id = new.actor_id and action = 'auth.failed_2fa' and created_at > now() - interval '10 minutes';
    if v_n + 1 >= 3 and not exists (select 1 from public.audit_alerts where rule_key = 'failed_2fa' and actor_id = new.actor_id and status <> 'closed' and created_at > now() - interval '1 hour') then
      insert into public.audit_alerts (rule_key, severity, title, detail, actor_id, subject)
      values ('failed_2fa', 'high', 'Failed 2FA burst', analytics_private.short_name(v_name) || ' entered ' || (v_n + 1) || ' wrong 2FA codes in 10 min', new.actor_id, '≥ 3 wrong codes in 10 min');
    end if;
  end if;

  if new.action = 'admin.role_change' and new.metadata ->> 'to_role' in ('admin', 'super_admin')
     and coalesce((select enabled from public.admin_alert_rules where key = 'role_escalation'), true) then
    insert into public.audit_alerts (rule_key, severity, title, detail, actor_id, subject)
    values ('role_escalation', 'high', 'Role escalation', coalesce(new.metadata ->> 'summary', 'A role was raised to ' || (new.metadata ->> 'to_role')), new.actor_id, new.resource);
  end if;
  return new;
end;
$$;

create trigger audit_log_detect_after_insert
  after insert on public.audit_log
  for each row execute function public.audit_detect();

-- Anyone (also before sign-in) can report a failed login; rate-limited per IP so it can't flood the log.
create function public.log_auth_failure(p_email text)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_ip text := analytics_private.request_ip();
begin
  if (select count(*) from public.audit_log where action = 'auth.failed_login' and coalesce(ip, '') = coalesce(v_ip, '') and created_at > now() - interval '1 hour') >= 30 then
    return;
  end if;
  insert into public.audit_log (actor_email, action, resource, metadata)
  values (null, 'auth.failed_login', left(lower(trim(coalesce(p_email, 'unknown'))), 120), jsonb_build_object('summary', 'Failed sign-in'));
end;
$$;
revoke execute on function public.log_auth_failure(text) from public;
grant execute on function public.log_auth_failure(text) to anon, authenticated;
